export type IconName = keyof typeof ICONS;

interface Props extends Omit<IconProps, 'name'> {
  name: IconName;
}

export const Icon: React.FC<Props> = ({ name, size = 20, color = Colors.textSecondary, weight = 'regular', ...rest }) => {
  const Glyph = ICONS[name];
  return <Glyph size={size} color={color} weight={weight} {...rest} />;
};

/** Category slug -> icon name, shared by walks, events and places. */
export function categoryIcon(category?: string): IconName {
  const key = (category ?? '').toLowerCase().replace(/[^a-z]/g, '');
  const map: Record<string, IconName> = {
    park: 'park', trail: 'trail', lake: 'lake', beach: 'beach', cafe: 'cafe', caf: 'cafe', city: 'city',
    meetup: 'meetup', playdate: 'playdate', competition: 'competition', wellness: 'wellness', walk: 'night',
    vet: 'vet', store: 'store', walks: 'walk', parks: 'park', cafes: 'cafe', vets: 'vet', trails: 'trail',
  };
  return map[key] ?? 'pin';
}
